import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const directory = fileURLToPath(new URL('.', import.meta.url));
await build({
  absWorkingDir: directory,
  entryPoints: ['component.source.js'],
  outfile: 'component.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  loader: { '.css': 'text' },
  minify: true,
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: '// Generated by npm run build. Edit component.source.js and its imported assets.' },
});
const output = await readFile(new URL('component.js', import.meta.url));
console.log(`component.js: ${output.length} bytes; gzip: ${gzipSync(output).length} bytes; one static request`);
